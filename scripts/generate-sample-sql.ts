/**
 * Regenerates supabase/migrations/0002_sample_trips.sql from the sample
 * trip generator in src/lib/sampleTrips.ts.
 *
 *   npx tsx scripts/generate-sample-sql.ts
 *
 * The dates are fixed here; the app shifts them to "yesterday and the day
 * before" when it copies them into a new account.
 */
import { writeFileSync } from 'node:fs'
import { generateSampleTrips } from '../src/lib/sampleTrips'

const REFERENCE_NOW = Date.UTC(2026, 10, 4, 12) // 4 Nov 2026
const trips = generateSampleTrips('', REFERENCE_NOW)

const sqlString = (s: string) => `'${s.replaceAll("'", "''")}'`

const values = trips
  .map((trip, i) => {
    const { id, ...rest } = trip
    return `  (${sqlString(id)}, ${i + 1}, ${sqlString(JSON.stringify({ id, ...rest }))}::jsonb)`
  })
  .join(',\n')

const sql = `-- Trip Consumption Analysis — shared sample trips.
-- Run once in the Supabase SQL editor, after 0001_trips.sql. Safe to re-run.
--
-- Every user can read these (signed in or not); nobody can change them
-- through the app. A brand-new account gets a copy of them in its own
-- trips (re-dated to the last two days), and "Add sample trips" on the
-- Account page copies them again.
--
-- To change the sample data, edit rows here or in Supabase → Table Editor →
-- sample_trips (the \`data\` column holds the trip JSON exactly as the app
-- stores it). Generated by scripts/generate-sample-sql.ts.

create table if not exists public.sample_trips (
  id         text primary key check (id like 'sample-%'),
  sort_order int  not null default 0,
  data       jsonb not null
);

alter table public.sample_trips enable row level security;

drop policy if exists "sample_trips: read all" on public.sample_trips;
create policy "sample_trips: read all" on public.sample_trips
  for select to anon, authenticated
  using (true);

revoke all on public.sample_trips from anon, authenticated;
grant select on public.sample_trips to anon, authenticated;

insert into public.sample_trips (id, sort_order, data) values
${values}
on conflict (id) do update set sort_order = excluded.sort_order, data = excluded.data;
`

writeFileSync(new URL('../supabase/migrations/0002_sample_trips.sql', import.meta.url), sql)
console.log(`Wrote ${trips.length} sample trips (${sql.length} bytes).`)
